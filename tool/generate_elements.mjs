// Writes lib/content/elements.g.dart from Bowserinator/Periodic-Table-JSON
// (CC BY-SA 3.0, data from Wikipedia). Usage: node tool/generate_elements.mjs <PeriodicTableJSON.json>
import fs from 'fs';
const source = JSON.parse(fs.readFileSync(process.argv[2], 'utf8')).elements.filter((e) => e.number <= 118);
const text = (value) => value == null ? 'null' : `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, ' ')}'`;
const number = (value) => value == null || Number.isNaN(Number(value)) ? 'null' : String(Number(value));
const lines = source.map((e) => `  ChemicalElement(number: ${e.number}, symbol: ${text(e.symbol)}, name: ${text(e.name)}, atomicMass: ${number(e.atomic_mass)}, category: ${text(e.category)}, group: ${e.group}, period: ${e.period}, column: ${e.xpos}, row: ${e.ypos}, phase: ${text(e.phase)}, block: ${text(e.block)}, electronConfiguration: ${text(e.electron_configuration_semantic)}, shells: <int>[${e.shells.join(', ')}], electronegativity: ${number(e.electronegativity_pauling)}, meltKelvin: ${number(e.melt)}, boilKelvin: ${number(e.boil)}, density: ${number(e.density)}, discoveredBy: ${text(e.discovered_by)}, namedBy: ${text(e.named_by)}, summary: ${text(e.summary)}, source: ${text(e.source)}),`);
fs.writeFileSync('lib/content/elements.g.dart', `// GENERATED by tool/generate_elements.mjs. Do not edit by hand.
// Data: Bowserinator/Periodic-Table-JSON, from Wikipedia, CC BY-SA 3.0
// (https://creativecommons.org/licenses/by-sa/3.0/).
import 'element.dart';

const List<ChemicalElement> elements = <ChemicalElement>[
${lines.join('\n')}
];
`);
console.log('wrote', source.length);
